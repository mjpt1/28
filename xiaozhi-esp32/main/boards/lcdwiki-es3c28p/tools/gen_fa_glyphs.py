# Renders the Persian words and digits used by the sleep/clock screen into
# 8-bit alpha bitmaps (fa_glyphs.h). The built-in LVGL fonts have no Persian
# digits or joined letter forms, so text is shaped here at build time.
#
# Usage: python gen_fa_glyphs.py <out.h>   (needs Pillow, Windows Tahoma font)
import sys
from PIL import Image, ImageDraw, ImageFont

FONT_DIR = "C:/Windows/Fonts/"

# Persian presentation forms: isolated, final, initial, medial (None = joins right only).
FORMS = {
    "ا": (0xFE8D, 0xFE8E, None, None), "آ": (0xFE81, 0xFE82, None, None),
    "ب": (0xFE8F, 0xFE90, 0xFE91, 0xFE92), "پ": (0xFB56, 0xFB57, 0xFB58, 0xFB59),
    "ت": (0xFE95, 0xFE96, 0xFE97, 0xFE98), "ج": (0xFE9D, 0xFE9E, 0xFE9F, 0xFEA0),
    "چ": (0xFB7A, 0xFB7B, 0xFB7C, 0xFB7D), "خ": (0xFEA5, 0xFEA6, 0xFEA7, 0xFEA8),
    "د": (0xFEA9, 0xFEAA, None, None), "ذ": (0xFEAB, 0xFEAC, None, None),
    "ر": (0xFEAD, 0xFEAE, None, None), "ز": (0xFEAF, 0xFEB0, None, None),
    "ژ": (0xFB8A, 0xFB8B, None, None), "س": (0xFEB1, 0xFEB2, 0xFEB3, 0xFEB4),
    "ش": (0xFEB5, 0xFEB6, 0xFEB7, 0xFEB8), "ع": (0xFEC9, 0xFECA, 0xFECB, 0xFECC),
    "ف": (0xFED1, 0xFED2, 0xFED3, 0xFED4), "ک": (0xFB8E, 0xFB8F, 0xFB90, 0xFB91),
    "گ": (0xFB92, 0xFB93, 0xFB94, 0xFB95), "ل": (0xFEDD, 0xFEDE, 0xFEDF, 0xFEE0),
    "م": (0xFEE1, 0xFEE2, 0xFEE3, 0xFEE4), "ن": (0xFEE5, 0xFEE6, 0xFEE7, 0xFEE8),
    "و": (0xFEED, 0xFEEE, None, None), "ه": (0xFEE9, 0xFEEA, 0xFEEB, 0xFEEC),
    "ی": (0xFBFC, 0xFBFD, 0xFBFE, 0xFBFF), "ط": (0xFEC1, 0xFEC2, 0xFEC3, 0xFEC4), "ق": (0xFED5, 0xFED6, 0xFED7, 0xFED8),
    "ص": (0xFEB9, 0xFEBA, 0xFEBB, 0xFEBC), "ح": (0xFEA1, 0xFEA2, 0xFEA3, 0xFEA4),
}


def shape(word):
    """Joins Persian letters and returns them in visual (left-to-right) order."""
    out = []
    chars = list(word)
    for i, c in enumerate(chars):
        if c not in FORMS:
            out.append(c if c != "\u200c" else "")
            continue
        prev = chars[i - 1] if i > 0 else None
        nxt = chars[i + 1] if i + 1 < len(chars) else None
        joins_prev = prev in FORMS and FORMS[prev][2] is not None
        joins_next = nxt in FORMS and FORMS[c][2] is not None
        iso, fin, ini, med = FORMS[c]
        if joins_prev and joins_next:
            f = med
        elif joins_prev:
            f = fin
        elif joins_next:
            f = ini
        else:
            f = iso
        out.append(chr(f))
    return "".join(reversed(out))


FA_DIGITS = "۰۱۲۳۴۵۶۷۸۹"
MONTHS = ["فروردین", "اردیبهشت", "خرداد", "تیر", "مرداد", "شهریور",
          "مهر", "آبان", "آذر", "دی", "بهمن", "اسفند"]
# tm_wday order: Sunday first.
WEEKDAYS = ["یکشنبه", "دوشنبه", "سه\u200cشنبه", "چهارشنبه", "پنجشنبه", "جمعه", "شنبه"]
WEATHER = ["صاف", "آفتابی", "نیمه\u200cابری", "ابری", "مه\u200cآلود", "نم\u200cنم باران",
           "بارانی", "برفی", "رگبار", "رعد و برق"]
CAR = ["کیلومتر بر ساعت", "دمای آب", "باتری", "خطای موتور", "جستجوی دانگل", "اتصال به خودرو",
       "دانگل پیدا نشد", "داغ کردن موتور", "باتری ضعیف", "دور موتور"]


def render_set(font_file, size, items):
    font = ImageFont.truetype(FONT_DIR + font_file, size)
    imgs = []
    for text in items:
        w = int(font.getlength(text)) + 8
        h = size * 2
        im = Image.new("L", (w, h), 0)
        ImageDraw.Draw(im).text((4, size // 2), text, font=font, fill=255)
        imgs.append(im)
    # Common vertical crop keeps one baseline for the whole set.
    top = min(im.getbbox()[1] for im in imgs if im.getbbox())
    bot = max(im.getbbox()[3] for im in imgs if im.getbbox())
    res = []
    for im in imgs:
        bb = im.getbbox() or (0, 0, 1, 1)
        res.append(im.crop((bb[0], top, bb[2], bot)))
    return res


def emit(f, name, imgs):
    for i, im in enumerate(imgs):
        data = ",".join(str(b) for b in im.tobytes())
        f.write(f"static const uint8_t {name}_{i}[] = {{{data}}};\n")
    f.write(f"static const FaGlyph {name}[] = {{\n")
    for i, im in enumerate(imgs):
        f.write(f"    {{{im.width}, {im.height}, {name}_{i}}},\n")
    f.write("};\n\n")


def main():
    out = sys.argv[1]
    big = render_set("tahoma.ttf", 92, list(FA_DIGITS) + [":"])
    small = render_set("tahomabd.ttf", 26, list(FA_DIGITS) + ["°", "٫"])
    words = render_set("tahomabd.ttf", 24, [shape(w) for w in MONTHS + WEEKDAYS + WEATHER + CAR])
    with open(out, "w", encoding="utf-8") as f:
        f.write("// Generated by tools/gen_fa_glyphs.py. Do not edit.\n#pragma once\n#include <cstdint>\n\n")
        f.write("struct FaGlyph { uint16_t w, h; const uint8_t* a; };\n\n")
        emit(f, "kFaBig", big)        # 0-9 digits, 10 ':'
        emit(f, "kFaSmall", small)    # 0-9 digits, 10 degree sign, 11 decimal point
        emit(f, "kFaWords", words)    # 0-11 months, 12-18 weekdays (Sun..Sat), 19.. weather
        f.write(f"constexpr int kFaWeekdayBase = {len(MONTHS)};\n")
        f.write(f"constexpr int kFaWeatherBase = {len(MONTHS) + len(WEEKDAYS)};\n")
        f.write(f"constexpr int kFaCarBase = {len(MONTHS) + len(WEEKDAYS) + len(WEATHER)};\n")


main()
