"""Make an LVGL 9 bitmap font (4 bpp) with Latin, Persian and the Arabic
presentation forms, so LVGL can show joined Persian letters.

    python tools/gen_lv_font_fa.py C:/Windows/Fonts/tahoma.ttf 18 font_fa_18.c

LVGL itself turns Persian text into presentation forms
(LV_USE_ARABIC_PERSIAN_CHARS); the font only has to contain them.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

ttf, size, out = sys.argv[1], int(sys.argv[2]), sys.argv[3]
name = out.rsplit("/", 1)[-1].rsplit("\\", 1)[-1].replace(".c", "")
font = ImageFont.truetype(ttf, size)

RANGES = [(0x20, 0x7E), (0xAB, 0xAB), (0xBB, 0xBB), (0x600, 0x6FF), (0x200C, 0x200F),
          (0xFB50, 0xFDFF), (0xFE70, 0xFEFF)]


def render(ch):
    x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
    w, h = x1 - x0, y1 - y0
    if w <= 0 or h <= 0:
        return None, 0, 0, 0, 0
    img = Image.new("L", (w, h), 0)
    ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
    return img, w, h, x0, -y1


notdef = render("\uFFFF")[0]
notdef_bytes = notdef.tobytes() if notdef else b""

glyphs = []  # (codepoint, bitmap bytes 4bpp, adv, w, h, ox, oy)
for a, b in RANGES:
    for cp in range(a, b + 1):
        ch = chr(cp)
        img, w, h, ox, oy = render(ch)
        if img is not None and notdef is not None and img.size == notdef.size and img.tobytes() == notdef_bytes:
            continue  # the font has no glyph for it
        adv = round(font.getlength(ch) * 16)
        if img is None:
            if cp in (0x20, 0x200C, 0x200D, 0x200E, 0x200F) or adv > 0:
                glyphs.append((cp, b"", adv, 0, 0, 0, 0))
            continue
        px = [v >> 4 for v in img.tobytes()]
        if len(px) % 2:
            px.append(0)
        data = bytes((px[i] << 4) | px[i + 1] for i in range(0, len(px), 2))
        glyphs.append((cp, data, adv, w, h, ox, oy))

asc, desc = font.getmetrics()
lines = [f"// Generated by tools/gen_lv_font_fa.py from {ttf.split('/')[-1]} {size}px. Do not edit.",
         '#include <lvgl.h>', "", "static const uint8_t glyph_bitmap[] = {"]
dsc = ["    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0},"]
idx = 0
for cp, data, adv, w, h, ox, oy in glyphs:
    if data:
        lines.append("    " + ",".join(f"0x{v:02x}" for v in data) + ",")
    dsc.append(f"    {{.bitmap_index = {idx}, .adv_w = {adv}, .box_w = {w}, .box_h = {h}, .ofs_x = {ox}, .ofs_y = {oy}}},")
    idx += len(data)
lines.append("    0};")
lines.append("static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {")
lines += dsc
lines.append("};")
start = glyphs[0][0]
lines.append("static const uint16_t unicode_list[] = {")
lines.append("    " + ",".join(str(g[0] - start) for g in glyphs) + "};")
lines += [
    "static const lv_font_fmt_txt_cmap_t cmaps[] = {",
    f"    {{.range_start = {start}, .range_length = {glyphs[-1][0] - start + 1}, .glyph_id_start = 1,",
    f"     .unicode_list = unicode_list, .glyph_id_ofs_list = NULL, .list_length = {len(glyphs)},",
    "     .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}};",
    "static const lv_font_fmt_txt_dsc_t font_dsc = {",
    "    .glyph_bitmap = glyph_bitmap, .glyph_dsc = glyph_dsc, .cmaps = cmaps, .kern_dsc = NULL,",
    "    .kern_scale = 0, .cmap_num = 1, .bpp = 4, .kern_classes = 0, .bitmap_format = 0};",
    f"const lv_font_t {name} = {{",
    "    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt, .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,",
    f"    .line_height = {asc + desc}, .base_line = {desc}, .subpx = LV_FONT_SUBPX_NONE,",
    "    .underline_position = -1, .underline_thickness = 1, .dsc = &font_dsc, .fallback = &lv_font_montserrat_14};",
]
open(out, "w", encoding="utf-8").write("\n".join(lines) + "\n")
print(f"{name}: {len(glyphs)} glyphs, {idx} bitmap bytes")
